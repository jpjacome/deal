## Reservas

- Algunas reservas se confirman al instante; otras quedan **pendientes** hasta que las confirmemos. Te avisamos por correo en ambos casos.
- Si no confirmamos una solicitud a tiempo, expira y el horario queda libre. Te avisaremos.
- El pago se realiza en el local.

## Cambios y cancelaciones

- Puedes cambiar o cancelar tu reserva desde el enlace "Mi reserva" que te enviamos, hasta las horas de anticipación indicadas para cada espacio.
- Después de ese plazo, escríbenos por WhatsApp.

## Asistencia

- Si no puedes venir, cancela para liberar el espacio a otra persona.
- Las inasistencias repetidas pueden hacer que tus próximas reservas requieran confirmación.

## Uso del espacio

- Respeta la capacidad y el horario reservados para que la siguiente persona encuentre el espacio listo a tiempo.
